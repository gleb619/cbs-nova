package cbs.nova.starter.temporal;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import cbs.nova.dsl.GlobalManager;
import cbs.nova.dsl.utils.DefinitionLoader;
import cbs.nova.dslexamples.v1.SampleProcessProcessDefinition;
import cbs.nova.dslexamples.v1.SimpleOrderProcessDefinition;
import cbs.nova.dslexamples.v1.SignalBranchProcessDefinition;
import io.temporal.testing.WorkflowReplayer;
import io.temporal.worker.NonDeterministicException;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Regression guard for Temporal workflow determinism. For each goldens JSON in
 * {@code src/test/resources/replay/}, replays the history through the corresponding generated
 * workflow implementation. A change to {@code ProcessCodeGenerator} (or to any template the
 * generated workflows delegate to) that silently reorders commands would surface here as a
 * {@link NonDeterministicException}, long before the change reaches a live cluster.
 *
 * <p>
 * Goldens are generated by {@link WorkflowReplayGoldensGenerator} (one-off, opt-in via system
 * property {@code cbs.nova.t770.regenerate-goldens=true}). Regenerate only when a change is
 * intentionally replay-incompatible and call it out in the commit message.
 */
class WorkflowReplayGuardTest {

  private static final Path GOLDENS_DIR = Path.of("src/test/resources/replay");

  @BeforeEach
  void loadDslDefinitions() {
    // The replay re-runs the workflow class through `WorkflowReplayer`, which constructs the
    // generated `execute` body. The body delegates to `GlobalManager.runProcessWithCompensation`,
    // which needs `DefinitionLoader` outputs on the registry so `dslObject(...)` resolves a
    // `ProcessDslObject` for the workflow. None of the three golden examples invokes a helper or
    // a transaction, so registering Spring starter helpers (which require non-trivial constructor
    // arguments) is unnecessary and would surface as `NoSuchMethodException`.
    GlobalManager.globalManager().resetForTests();
    new DefinitionLoader().load(GlobalManager.globalManager());
  }

  @Test
  @DisplayName("SampleProcess golden history replays deterministically")
  void sampleProcessReplay() throws Exception {
    replayGolden("SampleProcess.json", SampleProcessProcessDefinition.class);
  }

  @Test
  @DisplayName("SimpleOrder golden history (with compensation) replays deterministically")
  void simpleOrderReplay() throws Exception {
    replayGolden("SimpleOrder.json", SimpleOrderProcessDefinition.class);
  }

  @Test
  @DisplayName("SignalBranch golden history (signal await) replays deterministically")
  void signalBranchReplay() throws Exception {
    replayGolden("SignalBranch.json", SignalBranchProcessDefinition.class);
  }

  @Test
  @DisplayName("Negative control: deliberately reordered workflow impl yields NonDeterministicException")
  void negativeControlDetectsMismatch() throws Exception {
    String history = readGolden("ReplayMismatchCanonical.json");
    // `WorkflowReplayer.replayWorkflowExecution` packages the Temporal SDK error into a
    // `RuntimeException("query failure for workflow_id ... error=...")`. The actual
    // `NonDeterministicException` is interpolated into the message rather than chained as the
    // cause, so we assert on the message text to prove the guard actually fails on a divergence.
    assertThatThrownBy(() -> WorkflowReplayer.replayWorkflowExecution(
            history, ReplayMismatchWorkflow.MisorderedImpl.class))
            .hasMessageContaining("NonDeterministicException");
  }

  private static void replayGolden(String fileName, Class<?> implClass) throws Exception {
    String history = readGolden(fileName);
    // `WorkflowReplayer.replayWorkflowExecution` instantiates the workflow through Temporal's
    // reflection-based factory and replays events from the JSON. Any deterministic mismatch
    // surfaces as `NonDeterministicException`. Activities are intentionally absent because the
    // three chosen examples do not invoke any transactions.
    WorkflowReplayer.replayWorkflowExecution(history, implClass);
  }

  private static String readGolden(String fileName) throws IOException {
    Path file = GOLDENS_DIR.resolve(fileName);
    assertThat(Files.exists(file))
            .as("Golden history %s must be present; run WorkflowReplayGoldensGenerator to regenerate",
                    file)
            .isTrue();
    return Files.readString(file);
  }
}
